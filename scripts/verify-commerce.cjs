const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
require.extensions['.ts'] = (module, filename) => {
  const source = fs.readFileSync(filename, 'utf8');
  module._compile(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, filename);
};
const memory = new Map();
global.window = globalThis;
Object.defineProperty(globalThis, 'localStorage', { configurable: true, value: { getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value), removeItem: key => memory.delete(key) } });
const { products, newArrivals, bags, partyHills } = require('../src/data/products.ts');
const { parseOrderInput } = require('../src/lib/order-input.ts');
const { useCartStore } = require('../src/store/useCartStore.ts');
assert.ok(newArrivals.length >= 4);
assert.equal(new Set(products.map(p => p.id)).size, products.length);
for (const p of products) assert.ok(fs.existsSync(path.join(__dirname, '../public', decodeURIComponent(p.image))), p.image);
const store = () => useCartStore.getState();
const product = bags[0];
const item = { id: product.id, name: product.title, image: product.image, price: product.price };
store().addItem(item, 2);
store().addItem(item, 3);
assert.equal(store().cart[0].quantity, 5);
assert.equal(store().getTotal(), product.price * 5);
store().updateQuantity(item.id, 0.5);
assert.equal(store().cart[0].quantity, 5);
store().addItem(item, -2);
assert.equal(store().cart[0].quantity, 5);
store().updateQuantity(item.id, 0);
assert.equal(store().cart.length, 0);
store().addItem(item, 99);
store().addItem(item, 1);
assert.equal(store().cart[0].quantity, 99);
store().clearCart();
const input = { customer: { name: 'Test Buyer', phone: '01700000000', address: 'Test delivery address', note: '' }, items: [{ id: product.id, quantity: 2 }] };
assert.equal(parseOrderInput(input).items[0].quantity, 2);
for (const quantity of [-1, 0, 0.5, 100]) assert.throws(() => parseOrderInput({ ...input, items: [{ id: product.id, quantity }] }));
assert.throws(() => parseOrderInput({ ...input, items: [...input.items, ...input.items] }));
assert.throws(() => parseOrderInput({ ...input, customer: { ...input.customer, address: '' } }));
assert.throws(() => parseOrderInput({ ...input, items: [] }));
console.log(`Passed: ${products.length} product IDs/images, ${newArrivals.length} arrivals, ${bags.length} bags, ${partyHills.length} footwear, cart totals/quantity limits, and checkout input validation.`);
